// Builds docs/patch-notes/patch-notes.js (an ES module for the future website) and checks docs/patch-notes/index.json against
// docs/patch-notes/patch-notes.json, the single source for the structured data.
//   node tools/build-patch-data.mjs
// There is no TypeScript toolchain in this repository, so the website-facing file is plain JavaScript with the same shape the site
// would use (`export const patchNotes = [...]`). index.json stays the small list (newest first) that points at each Markdown note.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'docs', 'patch-notes');
const data = JSON.parse(fs.readFileSync(path.join(dir, 'patch-notes.json'), 'utf8'));
const index = JSON.parse(fs.readFileSync(path.join(dir, 'index.json'), 'utf8'));

const problems = [];
if (data.length !== index.length) problems.push('index.json and patch-notes.json list a different number of versions');
data.forEach((d, i) => {
  const x = index[i];
  if (!x) return;
  for (const k of ['version', 'codename', 'title', 'date', 'status', 'tldr']) if (d[k] !== x[k]) problems.push(`${d.version}: "${k}" differs between index.json and patch-notes.json`);
  if (!fs.existsSync(path.join(dir, x.file))) problems.push(`${d.version}: ${x.file} does not exist`);
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const out = '// Generated by tools/build-patch-data.mjs from patch-notes.json. Do not edit by hand.\n' +
  'export const patchNotes = ' + JSON.stringify(data, null, 2) + ';\n';
fs.writeFileSync(path.join(dir, 'patch-notes.js'), out);
console.log('wrote docs/patch-notes/patch-notes.js (' + data.length + ' versions)');
